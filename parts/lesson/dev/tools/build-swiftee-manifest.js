// Regenerates js/swiftee-manifest.js from swiftee-assets/atlas/swiftee.manifest.json (the source of truth),
// keeping only what js/swiftee.js reads, so Swiftee also animates when index.html is opened from disk.
// Run from this folder: node dev/tools/build-swiftee-manifest.js
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..', '..');
const m = JSON.parse(fs.readFileSync(path.join(root, 'swiftee-assets/atlas/swiftee.manifest.json'), 'utf8'));
const out = { fps: m.fps, states: {}, standalone: m.standalone, animations: {}, scales: {} };
for (const k in m.states) out.states[k] = { start: m.states[k].start, loop: m.states[k].loop, stop: m.states[k].stop };
for (const k in m.animations) out.animations[k] = { pingpong: !!m.animations[k].pingpong };
for (const sc in m.scales) {
  out.scales[sc] = { sheets: {} };
  for (const k in m.scales[sc].sheets) {
    const s = m.scales[sc].sheets[k];
    out.scales[sc].sheets[k] = { cell: s.cell, frames: s.frames, cols: s.cols, image: s.image };
  }
}
// extra animations (swiftee-assets/extra/extra.json, e.g. 'measuring' from tools/build-measuring-sheet.js)
const extraFile = path.join(root, 'swiftee-assets/extra/extra.json');
if (fs.existsSync(extraFile)) {
  const ex = JSON.parse(fs.readFileSync(extraFile, 'utf8')).animations || {};
  for (const k in ex) {
    const a = ex[k];
    out.animations[k] = { pingpong: false, fps: a.fps };
    if (out.standalone.indexOf(k) < 0) out.standalone.push(k);
    for (const sc of ['1x', '2x']) out.scales[sc].sheets[k] = { cell: sc === '2x' ? 512 : 256, frames: a.frames, cols: a.cols, image: a.images[sc] };
  }
}
fs.writeFileSync(path.join(root, 'js/swiftee-manifest.js'),
  '// GENERATED by tools/build-swiftee-manifest.js from swiftee-assets/atlas/swiftee.manifest.json. Do not edit.\n' +
  'window.SWIFTEE_MANIFEST = ' + JSON.stringify(out) + ';\n');
console.log('wrote js/swiftee-manifest.js');
